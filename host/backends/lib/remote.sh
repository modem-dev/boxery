# shellcheck shell=bash disable=SC2154  # sourced by a backend (provides die/log/ROOT/…)
# Shared helpers for *remote* backends: VMs that live on a hosted platform (exe.dev, boat.dev, …) and
# are reached from the host through one supervised ssh tunnel per VM. See host/backends/README.md,
# "Remote backends".
#
# The backend sets, before calling anything here:
#   REMOTE_DIR         state root; per-VM state lives in $REMOTE_DIR/vms/NAME
#   REMOTE_SUPERVISOR  launchd | systemd   (runs and restarts the tunnels)
#   REMOTE_PORT_BASE   VM slot S ↔ host port REMOTE_PORT_BASE+S, the tunnel's -L end (the VM's endpoint)
#   REMOTE_MAX_SLOT    number of slots
#   REMOTE_PLATFORM    the platform's name, for messages (exe.dev, boat.dev)
#   REMOTE_CHECK       a command that checks the host can reach the platform, for messages
#   REMOTE_TUNNEL_WAIT seconds new/start/revert wait for a tunnel to connect (REMOTE_TUNNEL_WAIT_VAR: its setting)
# and defines:
#   remote_unit NAME   the tunnel's systemd unit / launchd label (without suffix); stable for NAME's life
#
# Tunnel model (every remote backend): `ssh -N … -L 127.0.0.1:PORT:127.0.0.1:22 -R 127.0.0.1:GPORT:127.0.0.1:PROXY_PORT`
# as the platform's admin user. -L is the VM's ssh endpoint (boxery-host only ever sees 127.0.0.1:PORT,
# as on Lima); -R gives the guest's boxery-llm a way back to the host's LLM proxy, so credentials stay on
# the host. Guest sshd only has to accept `agent` from loopback.

remote_vm_dir() { echo "$REMOTE_DIR/vms/$1"; }
remote_port() { echo $((REMOTE_PORT_BASE + $(cat "$(remote_vm_dir "$1")/slot"))); }

# ---------------------------------------------------------------- slots (host ports)
# Lowest free slot (1..REMOTE_MAX_SLOT), written to NAME's dir. Serialized: concurrent `new`s race here.
remote_alloc_slot() { # NAME → slot
	local lock=$REMOTE_DIR/.slot.lock i s used
	for i in $(seq 300); do take_lock "$lock" && break; sleep 0.1; [[ $i == 300 ]] && die "slot lock held ($lock)"; done
	used=" $(cat "$REMOTE_DIR"/vms/*/slot 2>/dev/null | tr '\n' ' ') "
	for ((s = 1; s <= REMOTE_MAX_SLOT; s++)); do [[ $used == *" $s "* ]] || break; done
	if ((s > REMOTE_MAX_SLOT)); then rm -f "$lock"; die "no free tunnel ports (max $REMOTE_MAX_SLOT VMs)"; fi
	echo "$s" >"$(remote_vm_dir "$1")/slot"
	rm -f "$lock"
	echo "$s"
}
# The slot lock is held for milliseconds; one older than a minute belongs to a dead holder. A fresh one
# may be a live `new`'s: leave it. (Crash recovery, backend_cleanup_new.)
remote_clear_stale_slot_lock() {
	local lock=$REMOTE_DIR/.slot.lock
	# -r: a lock left by an older boxery is a directory.
	if [[ -e $lock && -n $(find "$lock" -maxdepth 0 -mmin +1 2>/dev/null) ]]; then rm -rf "$lock"; fi
}

# ---------------------------------------------------------------- tunnels (supervised ssh)
# NAME DESCRIPTION ARGV…: write NAME's tunnel.sh (exec ARGV) and its supervisor definition (not started).
remote_tunnel_write() {
	local name=$1 desc=$2 d a; shift 2; d=$(remote_vm_dir "$name")
	{
		echo '#!/usr/bin/env bash'
		echo "# boxery: $desc. Generated by host/backends/lib/remote.sh."
		printf 'exec'
		for a in "$@"; do printf ' %q' "$a"; done
		echo
	} >"$d/tunnel.sh"
	chmod 755 "$d/tunnel.sh"
	if [[ $REMOTE_SUPERVISOR == launchd ]]; then
		cat >"$d/tunnel.plist" <<-EOF
			<?xml version="1.0" encoding="UTF-8"?>
			<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
			<plist version="1.0"><dict>
			  <key>Label</key><string>dev.$(remote_unit "$name")</string>
			  <key>ProgramArguments</key><array><string>$d/tunnel.sh</string></array>
			  <key>KeepAlive</key><true/><key>RunAtLoad</key><true/><key>ThrottleInterval</key><integer>5</integer>
			  <key>StandardErrorPath</key><string>$d/tunnel.log</string>
			</dict></plist>
		EOF
	else
		mkdir -p "$HOME/.config/systemd/user"
		cat >"$HOME/.config/systemd/user/$(remote_unit "$name").service" <<-EOF
			[Unit]
			Description=boxery VM $name ($desc)
			[Service]
			ExecStart=$d/tunnel.sh
			Restart=always
			RestartSec=5
			[Install]
			WantedBy=default.target
		EOF
		systemctl --user daemon-reload
	fi
}
remote_plist() { echo "$HOME/Library/LaunchAgents/dev.$(remote_unit "$1").plist"; }
# (Re)load a launch agent. bootout returns before launchd has removed the job, and a bootstrap in that
# window fails with "5: Input/output error": wait for it to go (5 s at most), and retry a failed bootstrap.
remote_launchd_reload() { # LABEL PLIST
	local domain i
	domain="gui/$(id -u)"
	launchctl bootout "$domain/$1" >/dev/null 2>&1 || true
	for ((i = 0; i < 50; i++)); do launchctl print "$domain/$1" >/dev/null 2>&1 || break; sleep 0.1; done
	for ((i = 1; i < 5; i++)); do launchctl bootstrap "$domain" "$2" 2>/dev/null && return; sleep 0.5; done
	launchctl bootstrap "$domain" "$2"
}
# Started tunnels are enabled (systemd) or installed in LaunchAgents (launchd), so they come back after
# a host reboot; remote VMs keep running while the host is down.
remote_tunnel_start() {
	if [[ $REMOTE_SUPERVISOR == launchd ]]; then
		mkdir -p "$HOME/Library/LaunchAgents"
		cp "$(remote_vm_dir "$1")/tunnel.plist" "$(remote_plist "$1")"
		remote_launchd_reload "dev.$(remote_unit "$1")" "$(remote_plist "$1")" || die "starting the tunnel to $1 failed"
	else
		systemctl --user enable "$(remote_unit "$1").service" >/dev/null 2>&1 || die "enabling the tunnel to $1 failed"
		# restart, not start: reimage and start rewrite tunnel.sh for a running unit
		systemctl --user restart "$(remote_unit "$1").service" || die "starting the tunnel to $1 failed (journalctl --user -u $(remote_unit "$1"))"
	fi
}
remote_tunnel_stop() {
	if [[ $REMOTE_SUPERVISOR == launchd ]]; then
		launchctl bootout "gui/$(id -u)/dev.$(remote_unit "$1")" >/dev/null 2>&1 || true
		rm -f "$(remote_plist "$1")"
	else
		systemctl --user disable --now "$(remote_unit "$1").service" >/dev/null 2>&1 || true
	fi
}
remote_tunnel_active() {
	if [[ $REMOTE_SUPERVISOR == launchd ]]; then launchctl print "gui/$(id -u)/dev.$(remote_unit "$1")" >/dev/null 2>&1
	else systemctl --user is-active --quiet "$(remote_unit "$1").service"; fi
}
# Supervised at all: launchd has the agent, or the unit is enabled (it is "inactive" between restarts).
remote_tunnel_loaded() {
	if [[ $REMOTE_SUPERVISOR == launchd ]]; then remote_tunnel_active "$1"
	else systemctl --user is-enabled --quiet "$(remote_unit "$1").service"; fi
}
# Local checks only (no API call), cheap enough for ls and connect:
#   up         supervised, and the -L end accepts connections: ssh is connected to the platform
#   connecting supervised, not connected: the host is offline or just woke from sleep, the platform is
#              unreachable, or the VM was stopped outside boxery. The supervisor retries every 5s.
#   down       not supervised: the VM is stopped, or the unit/agent was removed by hand
remote_tunnel_state() {
	remote_tunnel_loaded "$1" || { echo down; return; }
	if remote_tunnel_active "$1" && nc -z 127.0.0.1 "$(remote_port "$1")" >/dev/null 2>&1; then echo up; else echo connecting; fi
}
remote_tunnel_log() { # NAME → where the tunnel's ssh errors go
	if [[ $REMOTE_SUPERVISOR == launchd ]]; then echo "$(remote_vm_dir "$1")/tunnel.log"; else echo "journalctl --user -u $(remote_unit "$1") _COMM=ssh"; fi
}
remote_tunnel_last_error() {
	if [[ $REMOTE_SUPERVISOR == launchd ]]; then tail -n 1 "$(remote_vm_dir "$1")/tunnel.log" 2>/dev/null
	# _COMM=ssh: ssh's own stderr (tunnel.sh execs ssh), not systemd's "Scheduled restart job" lines
	else journalctl --user -u "$(remote_unit "$1")" _COMM=ssh -n 1 -o cat --no-pager 2>/dev/null; fi
}
remote_tunnel_remove() {
	remote_tunnel_stop "$1"
	if [[ $REMOTE_SUPERVISOR != launchd ]]; then
		rm -f "$HOME/.config/systemd/user/$(remote_unit "$1").service"
		systemctl --user daemon-reload 2>/dev/null || true
	fi
}
# Why NAME's endpoint can't be reached (backend_endpoint_problem, see README; no API call): prints nothing
# and returns 0 when the tunnel is up; 1 = it is reconnecting and may recover; 2 = there is no tunnel.
# Either way the VM has no ssh endpoint and its agents have no LLM proxy: both ride the tunnel.
remote_endpoint_problem() {
	[[ -f $(remote_vm_dir "$1")/slot ]] || { echo "no such vm: $1"; return 2; }
	case $(remote_tunnel_state "$1") in
	up) return 0 ;;
	down) echo "$1 is stopped, or its ssh tunnel isn't running (no ssh, no LLM proxy). Fix: boxery-host start $1"; return 2 ;;
	esac
	local last; last=$(remote_tunnel_last_error "$1" | tr -d '\r' | cut -c1-200) || last=""
	echo "the ssh tunnel to $1 isn't connected to $REMOTE_PLATFORM${last:+ (last error: $last)}; until it is, $1 has no ssh and its agents have no LLM proxy.
  $REMOTE_SUPERVISOR retries every 5s. Is this host online and awake? Check: $REMOTE_CHECK; log: $(remote_tunnel_log "$1").
  If it was stopped outside boxery or doesn't recover: boxery-host start $1"
	return 1
}
# The two ends boxery-host needs: backend_ssh_endpoint (no API call: `connect` runs it for every ssh
# session) and backend_wait_endpoint (the tunnel's local end is up; ssh readiness through it is
# boxery-host's wait).
remote_ssh_endpoint() {
	[[ -f $(remote_vm_dir "$1")/slot ]] || die "no such vm: $1"
	local msg; msg=$(remote_endpoint_problem "$1") || die "$msg"
	echo "127.0.0.1 $(remote_port "$1")"
}
remote_wait_endpoint() {
	local rc msg=""
	[[ $REMOTE_TUNNEL_WAIT =~ ^[1-9][0-9]*$ ]] || die "${REMOTE_TUNNEL_WAIT_VAR:-the tunnel wait} must be a number of seconds >= 1 (got '$REMOTE_TUNNEL_WAIT')"
	[[ -f $(remote_vm_dir "$1")/slot ]] || die "no such vm: $1"
	for _ in $(seq "$REMOTE_TUNNEL_WAIT"); do
		rc=0; msg=$(remote_endpoint_problem "$1") || rc=$?
		case $rc in
		0) echo "127.0.0.1 $(remote_port "$1")"; return ;;
		2) die "$msg" ;;
		esac
		sleep 1
	done
	die "timed out after ${REMOTE_TUNNEL_WAIT}s: $msg"
}

# ---------------------------------------------------------------- base build
# The guest side of the base build, as one root script: the agent user (hosted images have no
# cloud-init), $BASE_USERDATA (image/base-user-data.yaml with the layers filled in), then the backend's post-build script (from POST_FN), run
# detached from the ssh session so a dropped connection doesn't kill it. Progress: /var/log/boxery-build.log;
# POST_FN's script touches OK_MARKER at its end, and the run touches /var/log/boxery-build.done.
remote_build_script() { # POST_FN OK_MARKER [EXTRA_PRE_COMMAND…] → script on stdout
	local post=$1 okm=$2 c; shift 2
	echo 'set -e'
	echo 'id agent >/dev/null 2>&1 || useradd -m -s /bin/bash -c "boxery agent" -G sudo,adm agent'
	echo 'echo "agent ALL=(ALL) NOPASSWD:ALL" >/etc/sudoers.d/90-boxery-agent; chmod 440 /etc/sudoers.d/90-boxery-agent'
	"${BOXERY_NODE:-node}" "$ROOT/host/cloudconfig-sh.mjs" "$BASE_USERDATA" || return 1
	echo 'cat >/usr/local/sbin/boxery-remote-post.sh <<'"'"'BOXERY_POST'"'"
	"$post"
	echo 'BOXERY_POST'
	echo 'chmod 755 /usr/local/sbin/boxery-remote-post.sh'
	echo "rm -f /var/log/boxery-build.ok $okm /var/log/boxery-build.done"
	for c in "$@"; do echo "$c"; done
	echo 'setsid nohup bash -c "export DEBIAN_FRONTEND=noninteractive; { apt-get update -qq && /usr/local/sbin/boxery-build.sh && /usr/local/sbin/boxery-remote-post.sh; } >/var/log/boxery-build.log 2>&1; touch /var/log/boxery-build.done" </dev/null >/dev/null 2>&1 &'
}
# Poll a detached build until OK_MARKER (ok) or the done marker without it (failed). RUN_FN VM CMD runs
# CMD in the builder as its admin user. Prints ok | failed; dies after BOXERY_REMOTE_BUILD_TIMEOUT (2400 s).
remote_build_wait() { # RUN_FN VM OK_MARKER POLL_SECONDS
	local run=$1 vm=$2 okm=$3 poll=$4 t=0 st
	while :; do
		st=$("$run" "$vm" "if [ -f $okm ]; then echo ok; elif [ -f /var/log/boxery-build.done ]; then echo failed; else echo running; fi" </dev/null 2>/dev/null) || st=unreachable
		case $st in ok | failed) echo "$st"; return 0 ;; esac
		((t > ${BOXERY_REMOTE_BUILD_TIMEOUT:-2400})) && return 1
		sleep "$poll"; t=$((t + poll)); ((t % 60 < poll)) && log "still building... ${t}s"
	done
}

# Post-build pieces most hosted images need, as root-script text (heredocs inside the post script).
# Start the agent user's systemd manager (desktop, VNC, noVNC) at boot, whether or not logind does.
remote_post_agent_session() {
	cat <<-'EOF'
		cat >/etc/systemd/system/boxery-agent-session.service <<-UNIT
			[Unit]
			Description=boxery: start the agent user's systemd manager (desktop services)
			After=systemd-user-sessions.service
			[Service]
			Type=oneshot
			RemainAfterExit=yes
			ExecStart=/bin/systemctl start user@$(id -u agent).service
			[Install]
			WantedBy=multi-user.target
		UNIT
		systemctl enable boxery-agent-session.service
	EOF
}
# A boot unit UNIT running SCRIPT (both under /usr/local/sbin and /etc/systemd/system) with BODY: what
# the platform resets at every boot (hostname, filesystem size). BODY ends up in a /bin/sh script.
remote_post_boot_unit() { # UNIT DESCRIPTION SCRIPT BODY
	printf "cat >%s <<-'SH'\n#!/bin/sh\n%s\nSH\n" "$3" "$4"
	printf 'chmod 755 %s\n' "$3"
	printf "cat >/etc/systemd/system/%s.service <<-'UNIT'\n" "$1"
	printf '[Unit]\nDescription=%s\nBefore=ssh.service boxery-agent-session.service\n[Service]\nType=oneshot\nRemainAfterExit=yes\nExecStart=%s\n[Install]\nWantedBy=multi-user.target\nUNIT\n' "$2" "$3"
	printf 'systemctl enable %s.service\n' "$1"
}
# The boot-script body that restores boxery's hostname (from /etc/boxery/hostname, written by the
# identity step) when the platform resets it.
remote_hostname_restore() {
	cat <<-'EOF'
		[ -s /etc/boxery/hostname ] || exit 0
		n=$(cat /etc/boxery/hostname)
		hostname "$n"; echo "$n" >/etc/hostname
		grep -q "[[:space:]]$n\$" /etc/hosts || echo "127.0.1.1 $n" >>/etc/hosts   # sudo resolves it
	EOF
}

# ---------------------------------------------------------------- identity
# Per-VM identity as one root script: what cloud-init would do with boxery_seed's user-data. Keys
# replace authorized_keys (a fork never keeps its source's lease holder), a fresh machine-id, the
# hostname (now and at every boot, through BOOT_SCRIPT), then the runcmd steps. Piped to the guest,
# never written to disk: it carries the proxy token.
#   HOST_KEYS=regen  also regenerate the ssh host keys (a copied disk carries its source's); "keep" when
#                    the platform gives every machine its own and pins it through its API (boat.dev)
remote_identity_script() { # USERDATA NAME BOOT_SCRIPT HOST_KEYS
	echo 'set -e'
	"${BOXERY_NODE:-node}" "$ROOT/host/cloudconfig-sh.mjs" "$1" || return 1
	echo 'install -d -m 700 -o agent -g agent /home/agent/.ssh'
	echo "cat >/home/agent/.ssh/authorized_keys <<'BOXERY_KEYS'"
	awk '/^ssh_authorized_keys:/{f=1;next} f&&/^  - /{sub(/^  - /,""); gsub(/^"|"$/,""); print; next} f{f=0}' "$1"
	echo 'BOXERY_KEYS'
	echo 'chown agent:agent /home/agent/.ssh/authorized_keys; chmod 600 /home/agent/.ssh/authorized_keys'
	echo 'rm -f /etc/machine-id /var/lib/dbus/machine-id; systemd-machine-id-setup >/dev/null 2>&1'
	# The pinned host key boxery-host put in the user-data (host/hostkeys.mjs) was written above with the
	# other files; sshd must pick it up. Without one (boat: the platform's key is pinned), regenerate the
	# copied disk's own keys unless the platform gives every machine its own.
	if grep -q '^  - path: /etc/ssh/boxery_host_ed25519_key$' "$1"; then echo 'rm -f /etc/ssh/ssh_host_*; ssh-keygen -A >/dev/null; systemctl restart ssh.service'
	elif [[ $4 == regen ]]; then echo 'rm -f /etc/ssh/ssh_host_*; ssh-keygen -A >/dev/null; systemctl restart ssh.service'; fi
	# Hostname (and /etc/hosts), now and at every boot: the platform resets them.
	printf 'mkdir -p /etc/boxery; echo %q >/etc/boxery/hostname; %s\n' "$2" "$3"
	echo 'rm -rf /run/user/*/boxery'
	echo 'chown -R agent:agent /home/agent'
	echo 'systemctl restart boxery-llm.service'
	echo 'uid=$(id -u agent); systemctl start "user@$uid.service"'
	# From agent's home: the script runs in the admin user's, and git reads the .git it finds there
	# (exeuntu's /home/exedev/.git, which agent can't read, makes every git config fail).
	echo "sudo -u agent bash -lc 'cd && git config --global user.name agent; git config --global user.email agent@boxery; git config --global init.defaultBranch main; mkdir -p ~/project && cd ~/project && { [ -d .git ] || git init -q; }'"
	echo '[ -e /etc/boxery/headless ] || sudo -u agent XDG_RUNTIME_DIR=/run/user/$uid systemctl --user start boxery-vnc boxery-desktop boxery-novnc || true'
}
