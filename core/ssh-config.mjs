// A host profile's ssh_config and host command line, as pure functions: the quoting OpenSSH and the
// shells in between need, and the file itself. Same output as the Bash controller's write_ssh_config was
// (test/ssh-config.test.mjs holds it to test/fixtures/bash-profile.sh, that code). No I/O here.

export const DEFAULT_HOST_BIN = "~/.local/bin/boxery-host";

/** One literal word for a POSIX shell: '…', with ' as '\''. Never lets a leading ~ expand. @param {string} s */
export const literal = (s) => `'${s.replaceAll("'", `'\\''`)}'`;
/** argv → one command line the remote shell splits back into exactly these words. @param {string[]} args */
export const literalArgs = (args) => args.map(literal).join(" ");
/** A path for the remote shell: only a leading ~ or ~/ expands (to "$HOME"), everything else is literal. @param {string} p */
export const remotePath = (p) => (p === "~" ? '"$HOME"' : p.startsWith("~/") ? `"$HOME"/${literal(p.slice(2))}` : literal(p));
/** A double-quoted local-shell word that also passes OpenSSH's ProxyCommand quote check. @param {string} s */
export const shellDouble = (s) => `"${s.replace(/[\\"$`]/g, (c) => `\\${c}`)}"`;
/** An ssh_config value (OpenSSH unquotes "…" with \ escapes and expands %). @param {string} s */
export const sshValue = (s) => `"${s.replace(/[\\"]/g, (c) => `\\${c}`).replaceAll("%", "%%")}"`;
/** One ssh_config argument whose percents are already escaped. @param {string} s */
export const sshWord = (s) => `"${s.replace(/[\\"]/g, (c) => `\\${c}`)}"`;
/** An Include path: glob characters literal too (Include expands globs after parsing). @param {string} s */
export const sshIncludeValue = (s) => sshValue(s.replace(/[\\*?[]/g, (c) => `\\${c}`));
/** ProxyCommand runs through a shell, KnownHostsCommand doesn't (ssh splits it and needs an absolute
 *  executable): run the same command line through /bin/sh, with %H as "$1". @param {string} proxy */
export const knownHostsCommand = (proxy) => `/bin/sh -c ${sshWord(`exec ${proxy} known-hosts "$1"`)} sh %H`;

export const VALID_DEST = /^(?!-)[A-Za-z0-9_.@:%+-]+$/;
const VALID_PROFILE = /^[a-z][a-z0-9-]{0,30}$/;
const PLAIN = /^[^\n\r\t]*$/;

/** Where boxery-host lives and how it's reached. @typedef {{ host: string, hostBin: string, hostProfile: string, identity: string }} Target */

/** The profile's target, checked as the controller's check_target does; throws its messages. @param {Target} t */
export function checkTarget(t) {
	if (!VALID_DEST.test(t.host)) throw new Error(`invalid ssh destination: ${t.host}`);
	if (!t.hostBin || t.hostBin.startsWith("-")) throw new Error("invalid host executable path");
	if (!PLAIN.test(t.hostBin)) throw new Error("paths cannot contain line breaks or tabs");
	if (t.hostProfile && !VALID_PROFILE.test(t.hostProfile)) throw new Error(`invalid host profile: ${t.hostProfile}`);
}
/** HOST=local: HOST_BIN on this machine (~/ is $HOME). @param {string} hostBin @param {string} home */
export const localHostBin = (hostBin, home) => (hostBin.startsWith("~/") ? `${home}/${hostBin.slice(2)}` : hostBin);
const profileArgs = (/** @type {Target} */ t) => (t.hostProfile ? ` --profile ${t.hostProfile}` : "");
/** The command ssh sends to a remote host for boxery-host ARGS. @param {Target} t @param {string[]} args */
export const remoteCommand = (t, args) => `exec ${remotePath(t.hostBin)}${profileArgs(t)} ${literalArgs(args)}`;

/**
 * The profile's ssh_config. leases: [{name, id}] (each lease's own key, in DIR/leases); agentVms: VMs
 * with an ssh-agent grant (ForwardAgent for them only); pins: the host pins VM host keys.
 * @param {Target & { dir: string, home: string, pins: boolean, leases: { name: string, id: string }[], agentVms: string[] }} p
 */
export function renderSshConfig(p) {
	const out = ["# generated by boxery setup — VMs are reached as <name>.boxery through the host"];
	// Leased pool VMs: that lease's own key (IdentitiesOnly so nothing else is offered).
	for (const l of p.leases) out.push(`Host ${l.name}.boxery`, `  IdentityFile ${sshValue(`${p.dir}/leases/${l.id}.key`)}`, "  IdentitiesOnly yes");
	// Per-VM ssh-agent grants. Never forward to the host.
	for (const vm of p.agentVms) out.push(`Host ${vm}.boxery`, "  ForwardAgent yes");
	out.push("Host *.boxery", "  ForwardAgent no", "  User agent");
	// ssh joins remote argv; the whole executable expression survives the local shell as one word.
	// OpenSSH expands percent tokens before the shell, so user-supplied percents are escaped.
	const proxy = (p.host === "local"
		? `${shellDouble(localHostBin(p.hostBin, p.home))}${profileArgs(p)}`
		: `ssh -o LogLevel=ERROR -- ${shellDouble(p.host)} ${shellDouble(`exec ${remotePath(p.hostBin)}${profileArgs(p)}`)}`).replaceAll("%", "%%");
	out.push(`  ProxyCommand ${proxy} connect %h %p`);
	if (p.pins) {
		// Each VM's host key is pinned on the host (host/hostkeys.mjs) and checked strictly: the host prints
		// the known_hosts line for %H. No local known_hosts: the host's record is the only one.
		out.push(`  KnownHostsCommand ${knownHostsCommand(proxy)}`, "  StrictHostKeyChecking yes", "  UserKnownHostsFile none",
			"  GlobalKnownHostsFile none", "  CheckHostIP no", "  UpdateHostKeys no");
	} else {
		// A host from before pinned keys: nothing to check against (the CLI's refresh upgrades this).
		out.push("  StrictHostKeyChecking no", "  UserKnownHostsFile /dev/null");
	}
	out.push("  LogLevel ERROR", "  ConnectTimeout 15", "  ServerAliveInterval 10", "  ServerAliveCountMax 3", "  ControlMaster auto",
		`  ControlPath ${sshValue(`${p.dir}/cm-`)}%h`, "  ControlPersist 10m");
	if (p.identity) out.push(`  IdentityFile ${sshValue(p.identity)}`);
	return `${out.join("\n")}\n`;
}

// ---------------------------------------------------------------- profile config
// A profile's `config` is a trusted shell file the CLI sources. What `boxery setup` writes is plain
// assignments to the controller's own settings (CONFIG_VARS), read here without a shell. parseConfig
// returns null for anything else (another variable, export, expansions, commands, unquoted ~), and the
// caller sources the file with bash instead: then any effect on the environment is the shell's own.

/** The settings a parsed config may set; any other name (PATH, HOME, IFS, exports…) means: source it. */
const CONFIG_VARS = ["HOST", "HOST_BIN", "HOST_PROFILE", "IDENTITY", "GRANT_CONFIRM"];

/** One shell word as setup writes it ('…' with '\'' for quotes, "…" without expansions, or plain), or null.
 *  @param {string} s */
export function shellWord(s) {
	let out = "";
	for (let i = 0; i < s.length;) {
		const c = s[i];
		if (c === "'") {
			const j = s.indexOf("'", i + 1);
			if (j < 0) return null;
			out += s.slice(i + 1, j); i = j + 1;
		} else if (c === '"') {
			const j = s.indexOf('"', i + 1);
			if (j < 0 || /[$`\\]/.test(s.slice(i + 1, j))) return null;
			out += s.slice(i + 1, j); i = j + 1;
		} else if (c === "\\" && i + 1 < s.length && s[i + 1] !== "\n") { out += s[i + 1]; i += 2; }
		else if (c === " " || c === "\t") return /^[ \t]*(#.*)?$/.test(s.slice(i)) ? out : null;
		else if (/[A-Za-z0-9_.@:%+\-/,=]/.test(c)) { out += c; i++; }
		else return null; // includes an unquoted ~, which an assignment would expand
	}
	return out;
}

/** The controller settings a plain config assigns (the last assignment wins, as when sourced), or null
 *  when the file needs a shell. @param {string} text @returns {Record<string, string> | null} */
export function parseConfig(text) {
	/** @type {Record<string, string>} */
	const out = {};
	for (const line of text.split("\n")) {
		if (/^[ \t]*(#.*)?$/.test(line)) continue;
		const m = /^[ \t]*([A-Za-z_][A-Za-z0-9_]*)=(.*)$/.exec(line);
		const value = m && CONFIG_VARS.includes(m[1]) ? shellWord(m[2]) : null;
		if (!m || value === null) return null;
		out[m[1]] = value;
	}
	return out;
}
